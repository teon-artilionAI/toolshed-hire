"""Initial schema: extensions, enum types, core tables and the overlap constraint.

Hand written rather than autogenerated. Alembic cannot invent an exclusion
constraint, so the one piece of DDL the whole design depends on would be
missing from a generated migration. The rest is written alongside it so the
schema is readable in one place.

The constraint text, the enum members and the extension list live in
app.infrastructure.schema_ddl, so the migration, the allocation use case and the
tests all read one definition instead of three copies.

Revision ID: 0001
Revises:
Created: 2026-08-15
"""

from __future__ import annotations

from collections.abc import Sequence

import sqlalchemy as sa
from sqlalchemy.dialects import postgresql

from alembic import op
from app.infrastructure.schema_ddl import (
    BRANCH_SCOPE_CHECK_DDL,
    ENUM_TYPES,
    EXCLUSION_CONSTRAINT_DDL,
    REFERENCE_SEQUENCE,
    REFERENCE_SEQUENCE_START,
    RELEASE_STATE_CHECK_DDL,
    REQUIRED_EXTENSIONS,
)

revision: str = "0001"
down_revision: str | None = None
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

def _uuid_pk() -> sa.Column[sa.Uuid]:
    """Return the standard application generated UUID primary key column."""
    return sa.Column("id", postgresql.UUID(as_uuid=True), primary_key=True, nullable=False)


def _enum(type_name: str, column_name: str = "status") -> sa.Column[str]:
    """Return a NOT NULL column bound to an enum type this migration created."""
    return sa.Column(
        column_name,
        postgresql.ENUM(*ENUM_TYPES[type_name], name=type_name, create_type=False),
        nullable=False,
    )


def _money(name: str) -> sa.Column[sa.Numeric]:
    """Return a NUMERIC(12,2) column. Money is never floating point."""
    return sa.Column(name, sa.Numeric(12, 2), nullable=False)


def _timestamps(*, with_updated: bool = True) -> list[sa.Column[sa.DateTime]]:
    """Return the standard created_at and updated_at columns."""
    columns = [
        sa.Column(
            "created_at",
            sa.DateTime(timezone=True),
            nullable=False,
            server_default=sa.text("now()"),
        )
    ]
    if with_updated:
        columns.append(
            sa.Column(
                "updated_at",
                sa.DateTime(timezone=True),
                nullable=False,
                server_default=sa.text("now()"),
            )
        )
    return columns


def _fk(name: str, target: str, *, nullable: bool = False) -> sa.Column[sa.Uuid]:
    """Return a UUID foreign key column. Nothing is ever hard deleted (BR-51)."""
    return sa.Column(
        name,
        postgresql.UUID(as_uuid=True),
        sa.ForeignKey(target, ondelete="RESTRICT"),
        nullable=nullable,
    )


