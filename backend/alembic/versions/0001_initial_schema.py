def downgrade() -> None:
    """Drop the tables, the sequence and the enum types, in dependency order.

    The extensions are left installed. They are database wide and may be in use
    by something else, so removing them would reach outside this migration.
    """
    op.execute(f"DROP SEQUENCE IF EXISTS {REFERENCE_SEQUENCE}")
    for table in (
        "asset_allocations",
        "reservation_lines",
        "reservations",
        "assets",
        "product_models",
        "user_accounts",
        "branches",
    ):
        op.drop_table(table)
    bind = op.get_bind()
    for type_name in reversed(list(ENUM_TYPES)):
        postgresql.ENUM(name=type_name).drop(bind, checkfirst=True)
